#!/usr/bin/env python3
"""Write each variant's hand-tuned theme files from its colors.toml.

Omarchy generates these from templates when a theme leaves them out. Rams
ships its own, so every surface follows the same few rules:

  - Honest surfaces: opaque, no blur, no shadow, no gradient.
  - Colour as signal: grey for structure, Braun orange for "this one" (focus,
    selection, the active thing), red only for errors.
  - One soft radius everywhere, like the corners of an SK 4 or an ET 66.
  - Calm motion: short, eased out, no overshoot.
  - Type does the work: Areal, a modest scale, generous spacing.

Usage: tools/build.py   (then `omarchy theme set rams` to see it)
"""
import json
