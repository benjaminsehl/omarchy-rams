def pi(c):
    """A quiet palette for the pi coding agent: ink and grey, orange for the
    thing that needs attention, green/red only for diffs and results."""
    fg, bg, acc = c["foreground"], c["background"], c["accent"]
    v = {
        "background": bg, "foreground": fg, "accent": acc,
        "ink": c["bright_foreground"],
        "selectionBackground": c["selection"], "selectionForeground": c["bright_foreground"],
        "selectedBackground": mix(bg, fg, 0.08),
        "color0": bg, "color1": c["red"], "color2": c["green"], "color3": c["yellow"],
        "color4": c["blue"], "color5": c["magenta"], "color6": c["cyan"], "color7": fg,
        "color8": c["muted"], "color9": c["bright_red"], "color10": c["bright_green"],
        "color11": c["bright_yellow"], "color12": c["bright_blue"], "color13": c["bright_magenta"],
        "color14": c["bright_cyan"], "color15": c["bright_foreground"],
        "brown": c["brown"],
        "panel": c["panel"], "panelAlt": c["panel_alt"],
        "panelPending": c["panel"],
        "panelSuccess": c["panel"],
        "panelError": mix(bg, c["red"], 0.10),
        "border": mix(bg, fg, 0.28), "borderMuted": c["hairline"],
        "mutedText": c["label"], "dimText": mix(fg, bg, 0.55),
    }
    colors = {
        "accent": "accent", "border": "border", "borderAccent": "accent", "borderMuted": "borderMuted",
        "success": "color2", "error": "color1", "warning": "accent",
        "muted": "mutedText", "dim": "dimText", "text": "foreground", "thinkingText": "dimText",
        "selectedBg": "selectedBackground",
        "userMessageBg": "panel", "userMessageText": "foreground",
        "customMessageBg": "panel", "customMessageText": "foreground", "customMessageLabel": "accent",
        "toolPendingBg": "panelPending", "toolSuccessBg": "panelSuccess", "toolErrorBg": "panelError",
        "toolTitle": "ink", "toolOutput": "foreground",
        "mdHeading": "ink", "mdLink": "accent", "mdLinkUrl": "mutedText",
        "mdCode": "brown", "mdCodeBlock": "foreground", "mdCodeBlockBorder": "borderMuted",
        "mdQuote": "mutedText", "mdQuoteBorder": "borderMuted", "mdHr": "borderMuted",
        "mdListBullet": "accent",
        "toolDiffAdded": "color2", "toolDiffRemoved": "color1", "toolDiffContext": "mutedText",
        # Syntax: mostly ink. Keywords carry weight by darkness, not hue;
        # strings and numbers get the only two colours.
        "syntaxComment": "dimText", "syntaxKeyword": "ink", "syntaxFunction": "foreground",
        "syntaxVariable": "foreground", "syntaxString": "color2", "syntaxNumber": "accent",
        "syntaxType": "brown", "syntaxOperator": "mutedText", "syntaxPunctuation": "mutedText",
        # Thinking levels climb from grey to Braun orange.
        "thinkingOff": "borderMuted", "thinkingMinimal": "dimText", "thinkingLow": "mutedText",
        "thinkingMedium": "foreground", "thinkingHigh": "brown", "thinkingXhigh": "accent",
        "bashMode": "accent",
    }
    return json.dumps({
        "$schema": "https://raw.githubusercontent.com/earendil-works/pi/main/packages/coding-agent/src/modes/interactive/theme/theme-schema.json",
        "name": "omarchy-system", "vars": v, "colors": colors,
        "export": {"pageBg": bg, "cardBg": c["panel"], "infoBg": c["panel_alt"]},
    }, indent=2) + "\n"


def btop(c):
    """Meters read like a Braun level indicator: grey while calm, ink as
    load rises, orange only at the top."""
    fg, bg, acc, mut = c["foreground"], c["background"], c["accent"], c["muted"]
    grey = c["label"]
    t = {
        "main_bg": bg, "main_fg": fg, "title": c["bright_foreground"], "hi_fg": acc,
        "selected_bg": c["selection"], "selected_fg": c["bright_foreground"],
        "inactive_fg": mut, "graph_text": grey, "meter_bg": c["hairline"],
        "proc_misc": grey, "div_line": c["hairline"],
        "cpu_box": c["hairline"], "mem_box": c["hairline"], "net_box": c["hairline"], "proc_box": c["hairline"],
        "temp_start": grey, "temp_mid": fg, "temp_end": acc,
        "cpu_start": grey, "cpu_mid": fg, "cpu_end": acc,
        "free_start": grey, "free_mid": grey, "free_end": fg,
        "cached_start": grey, "cached_mid": grey, "cached_end": fg,
        "available_start": grey, "available_mid": fg, "available_end": fg,
        "used_start": grey, "used_mid": fg, "used_end": acc,
        "download_start": grey, "download_mid": fg, "download_end": acc,
        "upload_start": grey, "upload_mid": fg, "upload_end": acc,
        "process_start": grey, "process_mid": fg, "process_end": acc,
    }
    lines = ["# Rams: generated by tools/build.py"]
    lines += [f'theme[{k}]="{v}"' for k, v in t.items()]
    return "\n".join(lines) + "\n"


def main():
    for d in VARIANTS:
        c = palette(d)
        for name, fn in [("hyprland.lua", hyprland), ("shell.toml", shell),
                         ("pi.json", pi), ("btop.theme", btop)]:
            (d / name).write_text(fn(c))
            print((d / name).relative_to(ROOT))


if __name__ == "__main__":
    main()
