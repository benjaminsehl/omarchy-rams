import tomllib

ROOT = pathlib.Path(__file__).resolve().parent.parent
VARIANTS = [ROOT, ROOT / "variants/dark"]

RADIUS = 6  # px; Hyprland rounding, which the Omarchy shell mirrors


def mix(a, b, t):
    """Mix hex colour a toward b by t (0..1)."""
    pa = [int(a[i:i + 2], 16) for i in (1, 3, 5)]
    pb = [int(b[i:i + 2], 16) for i in (1, 3, 5)]
    return "#" + "".join(f"{round(x + (y - x) * t):02x}" for x, y in zip(pa, pb))


def rgb(c):
    return f"rgb({c[1:]})"


def palette(path):
    c = tomllib.loads((path / "colors.toml").read_text())
    light = c["mode"] == "light"
    c["light"] = light
    # Structural greys, derived once so every file agrees.
    c["edge"] = "#" + c["hyprland_active_border"][4:-1]  # "rgb(3a3935)" -> "#3a3935"
    c["hairline"] = mix(c["background"], c["foreground"], 0.18)
    c["panel"] = mix(c["background"], c["foreground"], 0.05)
    c["panel_alt"] = mix(c["background"], c["foreground"], 0.09)
    c["label"] = mix(c["foreground"], c["background"], 0.40)
    c["inactive"] = c["lighter_background"] if light else mix(c["background"], c["foreground"], 0.12)
    # Shell surfaces sit on the clock dial, so they share its tone. Light:
    # the dial and the background are the same. Dark: the dial is noir.
    c["surface"] = c["background"] if light else "#0e0e0d"
    c["surface_hairline"] = mix(c["surface"], c["foreground"], 0.16)
    return c


